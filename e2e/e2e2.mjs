import { createRequire } from 'node:module';
const require = createRequire(process.env.PLAYWRIGHT_MODULE_DIR ?? import.meta.url);
const { chromium } = require('playwright');
const OUT = process.argv[2];
const errors = [];
const assert = (c, m) => { if (!c) { console.log('✗ FAIL:', m); process.exitCode = 1; } else console.log('✓', m); };
const browser = await chromium.launch();
const page = await (await browser.newContext({ viewport: { width: 1360, height: 900 } })).newPage();
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
const nav = (l) => page.locator('nav.nav button', { hasText: l }).click();
const yes = () => page.locator('.modal .btn.primary, .modal .btn.danger').click();
await page.goto('http://localhost:4173/');
await page.waitForSelector('nav.nav');

await nav('Maçlar');
await page.locator('.tab', { hasText: '4. Hafta' }).click();
for (const t of ['FB gol', 'LIV gol', 'GS gol', 'STU gol']) await page.getByLabel(t).fill('1');
await page.locator('.fixture', { hasText: 'Liverpool' }).first().locator('button', { hasText: 'Sonucu kaydet' }).click();
await page.locator('.fixture', { hasText: 'Stuttgart' }).first().locator('button', { hasText: 'Sonucu kaydet' }).click();
await page.locator('button', { hasText: 'Diğer Maçları Simüle Et' }).click();
await page.waitForTimeout(300);
assert(await page.locator('.tab.active', { hasText: '5. Hafta' }).count() === 1, 'Mod A: hafta tamamlanınca 5. haftaya geçildi');
assert(await page.locator('.fixture', { hasText: 'Barcelona' }).first().locator('.score-input').count() === 0, 'Mod A: FB/GS dışı maçlar elle düzenlenemez');
await page.locator('.tab', { hasText: '4. Hafta' }).click();
await page.getByLabel('FB gol').fill('3');
await page.locator('.fixture', { hasText: 'Liverpool' }).first().locator('button', { hasText: 'Sonucu kaydet' }).click();
await page.waitForSelector('.modal');
assert((await page.locator('.modal').innerText()).includes('1-1'), 'Elle sonucu değiştirmek onay istiyor');
await yes();

await page.locator('.mode-switch button', { hasText: 'Mod B' }).click();
await nav('Veri ve Ayarlar');
await page.getByLabel('Yeni senaryo adı').fill('Penaltı testi');
await page.locator('button', { hasText: 'Yeni senaryo' }).click();
await page.waitForTimeout(200);
assert((await page.locator('.scenario-pick select option:checked').innerText()) === 'Penaltı testi', 'Mod B: yeni senaryo oluşturuldu ve etkin');
await nav('Maçlar');
await page.locator('button', { hasText: 'Kalan Tüm Lig Maçlarını Simüle Et' }).click();
await page.waitForTimeout(800);
await nav('Turnuva Ağacı');
const tie = page.locator('.tie').first();
await tie.locator('button', { hasText: 'Skor gir' }).first().click();
await page.getByLabel('Ev sahibi gol').fill('1');
await page.getByLabel('Deplasman gol').fill('0');
await page.locator('.leg-editor button', { hasText: 'Kaydet' }).click();
await page.waitForTimeout(200);
await tie.locator('button', { hasText: 'Skor gir' }).first().click();
await page.getByLabel('Ev sahibi gol').fill('1');
await page.getByLabel('Deplasman gol').fill('0');
await page.locator('.leg-editor button', { hasText: 'Kaydet' }).click();
await page.waitForTimeout(200);
assert(await page.locator('.leg-editor').count() === 1, 'Toplam eşit ve uzatma yok → kayıt reddedildi');
await page.getByLabel('Uzatma ev').fill('0'); await page.getByLabel('Uzatma deplasman').fill('0');
await page.getByLabel('Penaltı ev').fill('5'); await page.getByLabel('Penaltı deplasman').fill('3');
await page.locator('.leg-editor button', { hasText: 'Kaydet' }).click();
await page.waitForTimeout(300);
const txt = await tie.innerText();
assert(txt.includes('penaltılarla') && txt.includes('pen. 5-3'), 'Penaltılı eleme sonucu elle girildi: ' + txt.replace(/\s+/g, ' ').slice(0, 170));
await page.locator('button', { hasText: 'Kalan tüm eleme maçlarını simüle et' }).click();
await page.waitForTimeout(500);
assert(await page.locator('[data-testid=champion]').count() === 1, 'Mod B: eleme sonuna kadar simüle edildi');
assert((await tie.innerText()).includes('pen. 5-3'), 'Elle girilen eleme sonucu simülasyonda korundu');
await page.screenshot({ path: `${OUT}/13-mod-b-eleme.png` });
await nav('Şampiyonluk Olasılıkları');
await page.waitForFunction(() => !document.body.innerText.includes('olasılıklar hesaplanıyor') && document.querySelectorAll('table.probs tbody tr').length > 0, null, { timeout: 30000 });
console.log('ilk satır', (await page.locator('table.probs tbody tr').first().innerText()).replace(/\s+/g, ' '));
await nav('Turnuva Ağacı');
const champBefore = await page.locator('[data-testid=champion]').innerText();
await page.locator('button', { hasText: 'Farklı tohumla yeniden oynat' }).click();
await yes();
await page.waitForTimeout(800);
console.log('önce', champBefore.replace(/\s+/g,' '), '| sonra', (await page.locator('[data-testid=champion]').innerText().catch(()=>'yok')).replace(/\s+/g,' '));
await page.locator('.mode-switch button', { hasText: 'Mod A' }).click();
await nav('Maçlar');
await page.locator('.tab', { hasText: '4. Hafta' }).click();
assert(await page.getByLabel('FB gol').inputValue() === '3', 'Mod B işlemleri Mod A’yı etkilemedi');
assert(errors.length === 0, 'Hata yok ' + errors.join('|'));
await browser.close();
